// Command docgen writes the PPL reference pages generated from the command,
// function and aggregation catalogs of pkg/ppl and the IR function registry:
//
//   - docs/site/docs/ppl/commands.md
//   - docs/site/docs/ppl/functions.md
//   - docs/site/docs/ppl/aggregations.md
//
// Run: go run ./internal/docgen
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/lynxbase/lynxdb/pkg/ir"
	"github.com/lynxbase/lynxdb/pkg/ppl"
)

func main() {
	root, err := repoRoot()
	if err == nil {
		err = Generate(root)
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "docgen: %v\n", err)
		os.Exit(1)
	}
}

// Pages maps each generated page, relative to the repository root, to its
// content.
func Pages() map[string]string {
	return map[string]string{
		"docs/site/docs/ppl/commands.md":     commandsPage(),
		"docs/site/docs/ppl/functions.md":    functionsPage(),
		"docs/site/docs/ppl/aggregations.md": aggregationsPage(),
	}
}

// Generate writes the generated pages under root.
func Generate(root string) error {
	for rel, content := range Pages() {
		if err := os.WriteFile(filepath.Join(root, rel), []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found above the working directory")
		}
		dir = parent
	}
}

const generatedNote = "<!-- Generated by go run ./internal/docgen from the PPL catalogs; do not edit. -->\n\n"

func header(title, label, position, description, intro string) string {
	return "---\ntitle: " + title + "\nsidebar_label: " + label + "\nsidebar_position: " + position +
		"\ndescription: " + description + "\n---\n\n" + generatedNote +
		"# " + title + "\n\n" + intro + "\n\n"
}

// cell makes s the text of a table cell that MDX reads as text.
func cell(s string) string {
	s = strings.NewReplacer("|", `\|`, "<", "&lt;", "{", "&#123;").Replace(s)
	return strings.ReplaceAll(s, "\n", " ")
}

func commandsPage() string {
	var b strings.Builder
	b.WriteString(header("PPL command reference", "Commands", "10",
		"Look up which OpenSearch PPL commands LynxDB supports, including command options, limits and differences.",
		"Every PPL command of the OpenSearch command reference and how LynxDB executes it. "+
			"*full* follows the OpenSearch semantics apart from the listed deviations; "+
			"*partial* runs with the listed options and limits and rejects the others with an "+
			"`UNSUPPORTED_FEATURE` error; *unsupported* commands fail with `UNSUPPORTED_COMMAND`."))
	b.WriteString("| Command | Support | Notes |\n|---|---|---|\n")
	for _, c := range ppl.Commands() {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", c.Name, c.Support, cell(c.Notes))
	}
	return b.String()
}

func functionsPage() string {
	var b strings.Builder
	b.WriteString(header("PPL scalar function reference", "Functions", "11",
		"Look up the OpenSearch PPL scalar functions LynxDB supports and how they map to its expression engine.",
		"Every PPL scalar function name. A name maps onto an IR registry function, is lowered "+
			"onto IR operators, or is unsupported and fails with `UNSUPPORTED_FUNCTION`. "+
			"NULL behavior and errors are those of the IR function."))
	b.WriteString("| Function | Category | Support | Semantics |\n|---|---|---|---|\n")
	for _, f := range ppl.ScalarFunctions() {
		category, doc, support := "", "", "full"
		switch {
		case f.Unsupported != "":
			support, doc = "unsupported", f.Unsupported
		case f.Lowering != "":
			doc = "lowered to " + f.Lowering
		}
		if fn, ok := ir.LookupFunc(f.IR); ok {
			category = fn.Category
			if doc == "" {
				doc = fn.Doc
			}
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", f.Name, category, support, cell(doc))
	}
	return b.String()
}

func aggregationsPage() string {
	var b strings.Builder
	b.WriteString(header("PPL aggregation function reference", "Aggregations", "12",
		"Look up the LynxDB PPL aggregation functions for stats, timechart and other commands, including how partial results combine.",
		"Aggregation functions of `stats`, `eventstats`, `streamstats`, `timechart` and `chart`. "+
			"*merge* tells how partial results of an aggregation combine."))
	b.WriteString("| Function | Support | Merge | Notes |\n|---|---|---|---|\n")
	for _, a := range ppl.AggregateFunctions() {
		support, notes, merge := "full", a.Note, ""
		if a.Unsupported != "" {
			support, notes = "unsupported", a.Unsupported
		}
		if fn, ok := ir.LookupFunc(a.IR); ok {
			merge = fmt.Sprint(fn.Merge)
			if notes == "" {
				notes = fn.Doc
			}
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", a.Name, support, merge, cell(notes))
	}
	return b.String()
}
